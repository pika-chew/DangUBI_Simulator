const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/cost-calculator.html','utf8');
const config=JSON.parse(fs.readFileSync(__dirname+'/seoul-cost-config.json','utf8'));
const embedded=JSON.parse(html.match(/<script id="default-config" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.deepEqual(embedded,config,'독립 HTML과 JSON 기본값 일치');
const source=html.match(/<script>\s*'use strict';([\s\S]*?)<\/script>/)[1];
const context=vm.createContext({});vm.runInContext(source,context);
const run=(override={},rates=config.rates)=>context.calculate({...config.scenario,...override},rates);
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-7,`${a} != ${b}`);
close(run().iot,129.677472);close(run().micro,108000000);
close(run({drivingBasis:'total',tripsPerDay:1/3}).iot,43.253472);
close(run({connectionMode:'full',retention:'active'}).connectionCost,.3456);
close(run({connectionMode:'full',retention:'continuous'}).connectionCost,4.1472);
assert.equal(run({messageBytes:5120}).billableChunks,1);
assert.equal(run({messageBytes:5121}).billableChunks,2);
close(context.tierCost(1e9,config.rates.messagePerMillion),1200);
close(context.tierCost(5e9,config.rates.messagePerMillion),5040);
close(context.tierCost(6e9,config.rates.messagePerMillion),5880);
close(run({existingMonthlyUnits:1e9}).messageCost,108030000*.96/1e6);
close(run({computeEnabled:true,otherUSD:5,retryPercent:1,reservePercent:20}).total,183.6557664);
close(run({drivingHours:0,tripsPerDay:0,retention:'active',poolWindowHours:0}).iot,0);
assert.throws(()=>run({days:31}));assert.throws(()=>run({days:0}));
assert.throws(()=>run({drivingHours:25}));assert.throws(()=>run({intervalSeconds:0}));
assert.throws(()=>run({retention:'custom',customHoldHours:1}));
assert.throws(()=>run({computeEnabled:true,workerHours:73}));
assert.ok(run({poolSize:1}).warnings.some(x=>x.includes('연결 풀')));
assert.ok(run({messageBytes:131073}).warnings.some(x=>x.includes('128KiB')));
assert.ok(run({peakActivePercent:1}).warnings.some(x=>x.includes('운행 비율')));
const compared=context.connectionComparisons(config.scenario,config.rates);
close(compared[0].result.holdHours,72);close(compared[1].result.holdHours,72);
close(compared[2].result.holdHours,72);close(compared[3].result.holdHours,6);
const sync=context.connectionComparisons({...config.scenario,poolWindowBasis:'synchronized'},config.rates);
close(sync[2].result.holdHours,6);close(sync[3].result.holdHours,6);
close(sync[2].result.connectionMinutes,36000);close(sync[2].result.connectionCost,.003456);
close(sync[2].result.iot,129.639456);
const spread=context.connectionComparisons({...config.scenario,poolWindowBasis:'distributed'},config.rates);
close(spread[0].result.connectionMinutes,spread[2].result.connectionMinutes);
assert.ok(sync.every(row=>Math.abs(row.result.messageCost-sync[0].result.messageCost)<1e-9));
close(run({poolWindowBasis:'custom',poolWindowHours:12,retention:'active'}).holdHours,12);
console.log('검증 통과: 기존 견적, 기준 전환, 연결 유지, 5KB 경계, 구간 단가, 실행비, 잘못된 입력 및 용량 경고');
